"""Keep Home available even when all three Django servers are stopped.

This HTTP service runs inside the launcher process. It renders the shared Home
template and manages only child processes that this launcher created.
"""

import json
import secrets
import subprocess
import sys
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse

from django.apps import apps
from django.conf import settings
from django.template import Context, Engine

from .catalog import PROJECTS, TITLES, task_project

APP_DIR = Path(__file__).resolve().parent
CONTROL_PORT = 7999


class ProcessManager:
    """Own server handles explicitly: never terminate an unrelated process."""

    def __init__(self, environment_factory, port_check):
        self.environment_factory = environment_factory
        self.port_check = port_check
        self.children = {}
        self.lock = threading.RLock()

    def state(self):
        with self.lock:
            return {
                project: {
                    "running": project in self.children
                    and self.children[project].poll() is None,
                    "pid": self.children[project].pid
                    if project in self.children
                    and self.children[project].poll() is None
                    else None,
                    "port": data["port"],
                }
                for project, data in PROJECTS.items()
            }

    def start(self, project):
        with self.lock:
            if self.state()[project]["running"]:
                return
            port = PROJECTS[project]["port"]
            if not self.port_check(port):
                raise RuntimeError(
                    f"Port {port} is occupied by another process. Stop it separately."
                )
            folder = APP_DIR.parent / project
            environment = {
                **self.environment_factory(project),
                "LESSON27_CONTROL_PORT": str(CONTROL_PORT),
            }
            # Existing migrations are applied to the demo database, never to
            # the homework database. No migrations are generated by this UI.
            subprocess.run(
                [sys.executable, "manage.py", "migrate", "--noinput"],
                cwd=folder,
                env=environment,
                check=True,
                timeout=60,
            )
            command = [
                sys.executable,
                "manage.py",
                "runserver",
                f"127.0.0.1:{port}",
                "--noreload",
            ]
            self.children[project] = subprocess.Popen(
                command, cwd=folder, env=environment
            )
            print(f"Started {project}: http://127.0.0.1:{port}/", flush=True)

    def stop(self, project):
        with self.lock:
            child = self.children.get(project)
            if child is None or child.poll() is not None:
                return
            child.terminate()
            try:
                child.wait(timeout=5)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait()
            print(f"Stopped {project}.", flush=True)

    def stop_all(self):
        for project in PROJECTS:
            self.stop(project)


def home_html(token):
    """Render the same Home template without configuring a fourth Django app.

    A standalone template Engine needs only static URL and localization settings.
    This process does not load ORM models or connect to a lesson database.
    """
    if not settings.configured:
        settings.configure(
            DEBUG=True, STATIC_URL="/static/", INSTALLED_APPS=[], USE_I18N=False
        )
    if not apps.ready:
        import django

        django.setup()
    engine = Engine(
        dirs=[str(APP_DIR / "templates")],
        libraries={"static": "django.templatetags.static"},
    )
    tasks = [
        {
            "number": n,
            "title": {"en": title[0], "pl": title[1]},
            "port": PROJECTS[task_project(n)]["port"],
            "backend": PROJECTS[task_project(n)]["backend"],
        }
        for n, title in TITLES.items()
    ]
    boot = {
        "number": None,
        "port": CONTROL_PORT,
        "tasks": tasks,
        "manager": True,
        "control_token": token,
        "control_port": CONTROL_PORT,
    }
    return (
        engine
        .get_template("cache_demo/home.html")
        .render(
            Context({
                "tasks": tasks,
                "project": "cache_demo",
                "backend": "Process controller",
                "port": CONTROL_PORT,
                "boot": boot,
                "manager": True,
            })
        )
        .encode("utf-8")
    )


def create_controller(manager):
    """Bind to loopback and require a per-launch token for process mutations."""
    token = secrets.token_urlsafe(32)
    html = home_html(token)

    class Handler(BaseHTTPRequestHandler):
        def valid_host(self):
            return self.headers.get("Host") in {
                f"127.0.0.1:{CONTROL_PORT}",
                f"localhost:{CONTROL_PORT}",
            }

        def send_data(self, status, data, content_type="application/json"):
            body = (
                json.dumps(data).encode("utf-8")
                if content_type == "application/json"
                else data
            )
            self.send_response(status)
            self.send_header("Content-Type", content_type + "; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Lesson27-Controller", "CacheLab")
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self):
            if not self.valid_host():
                return self.send_data(403, {"error": "Invalid host."})
            path = urlparse(self.path).path
            if path == "/":
                return self.send_data(200, html, "text/html")
            if path == "/control/status/":
                return self.send_data(200, manager.state())
            if path.startswith("/static/cache_demo/"):
                static_root = APP_DIR / "static" / "cache_demo"
                target = (
                    static_root / path.removeprefix("/static/cache_demo/")
                ).resolve()
                # Resolve and check containment before reading any requested file.
                if (
                    target.is_relative_to(static_root.resolve())
                    and target.is_file()
                    and target.suffix in {".css", ".js"}
                ):
                    content_type = (
                        "text/css"
                        if target.suffix == ".css"
                        else "text/javascript"
                    )
                    return self.send_data(
                        200, target.read_bytes(), content_type
                    )
            self.send_data(404, {"error": "Unknown route."})

        def do_POST(self):
            try:
                size = int(self.headers.get("Content-Length", "0"))
            except ValueError:
                return self.send_data(400, {"error": "Invalid request size."})
            if not 0 < size <= 1024:
                return self.send_data(400, {"error": "Invalid request size."})
            # Consume the bounded body before rejecting authorization. Leaving
            # unread bytes can turn a helpful 403 into a TCP reset on Windows.
            body = self.rfile.read(size)
            origin = self.headers.get("Origin")
            expected_origins = {
                f"http://127.0.0.1:{CONTROL_PORT}",
                f"http://localhost:{CONTROL_PORT}",
            }
            supplied = self.headers.get("X-Control-Token", "")
            # The token blocks CSRF; Host and Origin checks also reject requests
            # from arbitrary websites and DNS rebinding to this local service.
            if (
                not self.valid_host()
                or origin not in expected_origins
                or not secrets.compare_digest(supplied, token)
            ):
                return self.send_data(
                    403, {"error": "Controller request rejected."}
                )
            project = (
                urlparse(self.path).path.removeprefix("/control/").strip("/")
            )
            if project not in PROJECTS:
                return self.send_data(404, {"error": "Unknown project."})
            try:
                action = json.loads(body).get("action")
                if action == "start":
                    manager.start(project)
                elif action == "stop":
                    manager.stop(project)
                else:
                    raise ValueError("Unknown process action.")
                self.send_data(200, manager.state())
            except (ValueError, AttributeError) as error:
                self.send_data(400, {"error": str(error)})
            except (RuntimeError, subprocess.SubprocessError, OSError) as error:
                self.send_data(409, {"error": str(error)})

        def log_message(self, format, *args):
            # Process startup output is useful; repeated polling logs are noise.
            if self.command == "POST":
                super().log_message(format, *args)

    server = ThreadingHTTPServer(("127.0.0.1", CONTROL_PORT), Handler)
    server.daemon_threads = True
    return server
